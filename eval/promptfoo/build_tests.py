"""Builds classify_tests.yaml from eval/dataset/tickets.jsonl, so the prompt
regression set grows with the eval dataset instead of being kept by hand.
Multi-turn cases use the last turn as the message and the earlier turns as
history. Run by `make promptfoo` before every eval.
"""

import json
from pathlib import Path

import yaml

HERE = Path(__file__).resolve().parent
DATASET = HERE.parent / "dataset" / "tickets.jsonl"


def main() -> None:
    tests = []
    for line in DATASET.read_text().splitlines():
        if not line.strip():
            continue
        case = json.loads(line)
        if not case.get("expected_intent"):
            continue
        *earlier, last = case["turns"]
        history = "\n".join(f"customer: {t}" for t in earlier) or "(no prior messages)"
        tests.append({
            "description": f"classify: {case['id']}",
            "vars": {"task": "classify", "message": last, "history": history},
            "assert": [
                {"type": "is-json"},
                {
                    "type": "javascript",
                    "value": f"JSON.parse(output).intent === {json.dumps(case['expected_intent'])}",
                },
            ],
        })
    out = HERE / "classify_tests.yaml"
    out.write_text(
        "# Generated by build_tests.py from eval/dataset/tickets.jsonl - do not edit.\n"
        + yaml.safe_dump(tests, sort_keys=False, allow_unicode=True)
    )
    print(f"wrote {len(tests)} classify cases to {out.name}")


if __name__ == "__main__":
    main()
